#!/usr/bin/env python3
"""Turn aspa.json (rpki-client JSON style) into the files a router loads.

In production rpki-client writes these itself after validating the RPKI:
  rpki-client -B  ->  BIRD:     protocol static with "route aspa" entries
  rpki-client     ->  OpenBGPD: aspa-set { customer-as N provider-as { ... } }
The lab has no real RPKI repository, so the records come from aspa.json.
Run it after editing aspa.json:  python3 common/aspa/rpki/gen-aspa.py
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(here, "aspa.json")))
head = "# Generated by gen-aspa.py from aspa.json - do not edit\n"
bird = [head, "protocol static aspa_records {", "  aspa { table at; };"]
obgp = [head, "aspa-set {"]
for a in data["aspas"]:
    prov = a["providers"]
    bird.append(f"  route aspa {a['customer_asid']} providers {', '.join(map(str, prov))};")
    obgp.append(f"\tcustomer-as {a['customer_asid']} provider-as {{ {' '.join(map(str, prov))} }}")
bird.append("}")
obgp.append("}")
open(os.path.join(here, "aspa-bird.conf"), "w").write("\n".join(bird) + "\n")
open(os.path.join(here, "aspa-openbgpd.conf"), "w").write("\n".join(obgp) + "\n")
print(f"{len(data['aspas'])} ASPA records written")
